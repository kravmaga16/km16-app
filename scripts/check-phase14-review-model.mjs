import assert from 'node:assert/strict';
import {updateReview,REVIEW_STATES} from './phase14-review-model.mjs';
const date='2026-11-16T15:00:00Z';
assert.deepEqual(REVIEW_STATES,['a_verifier','en_cours','controle']);
const first=updateReview(null,'en_cours',0,'admin',date);
assert.equal(first.status.version,1);
assert.equal(first.event.previous_state,'a_verifier');
assert.equal(first.event.new_state,'en_cours');
const second=updateReview(first.status,'controle',1,'admin',date);
assert.equal(second.status.version,2);
assert.equal(second.event.previous_state,'en_cours');
const unchanged=updateReview(second.status,'controle',2,'admin',date);
assert.equal(unchanged.event,null);
assert.deepEqual(unchanged.status,second.status);
assert.throws(()=>updateReview(second.status,'a_verifier',1,'admin',date),/Conflit/);
assert.throws(()=>updateReview(null,'valide',0,'admin',date),/État invalide/);
assert.throws(()=>updateReview(null,'controle',-1,'admin',date),/Version invalide/);
assert.throws(()=>updateReview(null,'controle',0,'',date),/Administrateur/);
console.log('KM16 phase 14 model tests passed (simulation only, not SQL security tests)');
